'use strict';
const assert = require('assert');
const { createPopoutTabActivation } = require('../shell/core/popout-tab-activation');
const events = {}, disposed = [];
const win = { document: {}, addEventListener(name, fn) { events[name] = fn; }, removeEventListener(name, fn) { assert.strictEqual(events[name], fn); disposed.push(name); delete events[name]; } };
const tab = { ownerDocument: win.document, dataset: { tabPanelId: 'panel-a' } };
const target = { closest(selector) { return selector === '.dv-tab' ? tab : null; } };
let activated = 0;
const panel = { group: { element: { contains(node) { return node === tab; } } }, api: { setActive() { activated++; } } };
const binding = createPopoutTabActivation({ dockview: { getPanel(id) { return id === 'panel-a' ? panel : null; } } });
const detach = binding.attach(win);
function event(extra) { return { target, button: 0, detail: 1, clientX: 10, clientY: 10, ...extra }; }
events.pointerdown(event()); events.click(event());
assert.strictEqual(activated, 1, 'plain completed click activates synchronously without any animation/timer');
events.pointerdown(event()); events.dragstart(event()); events.click(event());
assert.strictEqual(activated, 1, 'drag completion must not change selected tab');
events.pointerdown(event()); events.pointermove(event({ clientX: 40 })); events.click(event());
assert.strictEqual(activated, 1, 'drag-like pointer movement ignored');
events.pointerdown(event({ shiftKey: true })); events.click(event({ shiftKey: true }));
assert.strictEqual(activated, 1, 'Shift gestures retained');
events.click(event({ detail: 0 }));
assert.strictEqual(activated, 2, 'keyboard-generated click remains available');
events.click(event({ defaultPrevented: true, detail: 0 }));
assert.strictEqual(activated, 2);
const action = { closest(selector) { return selector === '.dv-tab' ? tab : {}; } };
events.pointerdown(event({ target: action })); events.click(event({ target: action }));
assert.strictEqual(activated, 2, 'close and header buttons are not tab selection');
detach(); detach();
assert.strictEqual(Object.keys(events).length, 0);
assert.ok(disposed.length >= 4);
console.log('popout tab activation tests passed');
